#arithmetic operators
a = 7
b = 4

print(a + b)
print(a - b)
print(a *b)
print(a / b) #division (float result)
print(a // b) #floor division
print(a % b) #modulus (remainder)
print(a ** b) #exponentiation

#type checking
print(type(a))
print(type(a/b))

#working with float values
x = 7.4
y = 2
print(x + y)
print(x * y)

#complex number
c1 = 2 +3j
c2 = 3 + 2j
print(c1 + c2)
print(c1 * c2)
